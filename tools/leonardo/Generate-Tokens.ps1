<#
.SYNOPSIS
    Regenerates NAPS2.Lib/EtoForms/LeonardoTokens.g.cs from leonardo.tokens.json.

.DESCRIPTION
    Leonardo, the up in blue design language, ships its Windows values as XAML resources in
    UpInBlue.Leonardo.WinUI and UpInBlue.Leonardo.Wpf. ScanMe is WinForms, and referencing either
    package would pull WPF or the Windows App SDK into the app for a handful of constants, so the
    values are generated from the token file instead -- the same file those packages are built from.

    Only what the Windows outputs carry is written: a token whose $extensions.platforms does not
    name "windows" (the status colours, the web focus and accent hover/pressed colours) is skipped.
    Windows draws status in Fluent's colours, which stay in ColorScheme.

    To update Leonardo: replace leonardo.tokens.json with the file from upinblue/leonardo, note the
    version below, and re-run this script.

.EXAMPLE
    pwsh tools/leonardo/Generate-Tokens.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# The Leonardo release this token file corresponds to (NuGet UpInBlue.Leonardo.* 0.1.1).
$leonardoVersion = '0.1.1'

$toolDir  = $PSScriptRoot
$repoRoot = Split-Path (Split-Path $toolDir -Parent) -Parent
$source   = Join-Path $toolDir 'leonardo.tokens.json'
$target   = Join-Path $repoRoot 'NAPS2.Lib\EtoForms\LeonardoTokens.g.cs'

$tokens = Get-Content $source -Raw | ConvertFrom-Json -AsHashtable

function Test-Windows($token) {
    $ext = $token['$extensions']
    if (-not $ext -or -not $ext['platforms']) { return $true }
    return $ext['platforms'] -contains 'windows'
}

function Resolve-Color([string] $value) {
    if ($value -match '^\{palette\.(\w+)\}$') { return $tokens['palette'][$Matches[1]]['$value'] }
    if ($value -match '^\{') { throw "Unsupported reference $value" }
    return $value
}

function Get-Pascal([string] $name) { $name.Substring(0, 1).ToUpperInvariant() + $name.Substring(1) }

function Format-Color([string] $hex) {
    $hex = $hex.TrimStart('#')
    if ($hex.Length -ne 6) { throw "Unexpected colour #$hex" }
    "Color.FromRgb(0x$($hex.ToLowerInvariant()))"
}

function Write-ColorGroup($sb, [string] $className, $group) {
    [void]$sb.AppendLine("    public static class $className")
    [void]$sb.AppendLine('    {')
    foreach ($name in $group.Keys) {
        if ($name.StartsWith('$')) { continue }
        $token = $group[$name]
        if ($token -isnot [System.Collections.IDictionary] -or $token['$type'] -ne 'color') { continue }
        if (-not (Test-Windows $token)) { continue }
        $hex = Resolve-Color $token['$value']
        [void]$sb.AppendLine("        public static readonly Color $(Get-Pascal $name) = $(Format-Color $hex);")
    }
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine()
}

function Write-DimensionGroup($sb, [string] $className, $group) {
    [void]$sb.AppendLine("    public static class $className")
    [void]$sb.AppendLine('    {')
    foreach ($name in $group.Keys) {
        if ($name.StartsWith('$')) { continue }
        $token = $group[$name]
        if ($token['$type'] -ne 'dimension' -or -not (Test-Windows $token)) { continue }
        $member = if ($name.Length -le 2) { $name.ToUpperInvariant() } else { Get-Pascal $name }
        [void]$sb.AppendLine("        public const int $member = $($token['$value']['value']);")
    }
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine()
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine("// Generated by tools/leonardo/Generate-Tokens.ps1 from tools/leonardo/leonardo.tokens.json")
[void]$sb.AppendLine("// (Leonardo $leonardoVersion). Do not edit by hand; change the token file and re-run the script.")
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('using Eto.Drawing;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('namespace NAPS2.EtoForms;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('/// <summary>')
[void]$sb.AppendLine('/// The values of Leonardo, the up in blue design language, as far as the Windows outputs carry them.')
[void]$sb.AppendLine('/// Sizes are effective pixels at 96 dpi. Read colours through <see cref="ColorScheme"/>, which also')
[void]$sb.AppendLine('/// handles contrast themes; nothing else should reach into the theme classes directly.')
[void]$sb.AppendLine('/// </summary>')
[void]$sb.AppendLine('public static class LeonardoTokens')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine("    public const string Version = `"$leonardoVersion`";")
[void]$sb.AppendLine()

Write-ColorGroup $sb 'Palette' $tokens['palette']
Write-ColorGroup $sb 'Light' $tokens['theme']['light']
Write-ColorGroup $sb 'Dark' $tokens['theme']['dark']
Write-DimensionGroup $sb 'Space' $tokens['space']
Write-DimensionGroup $sb 'Radius' $tokens['radius']
Write-DimensionGroup $sb 'Density' $tokens['density']
Write-DimensionGroup $sb 'Size' $tokens['size']

[void]$sb.AppendLine('    /// <summary>The type roles on Windows: family, size and line height in epx, weight.</summary>')
[void]$sb.AppendLine('    public static class Type')
[void]$sb.AppendLine('    {')
foreach ($role in $tokens['typography'].Keys) {
    if ($role.StartsWith('$')) { continue }
    $win = $tokens['typography'][$role]['windows']
    if (-not $win) { continue }
    $p = Get-Pascal $role
    [void]$sb.AppendLine("        public static class $p")
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine("            public const string FontFamily = `"$($win['fontFamily'])`";")
    [void]$sb.AppendLine("            public const float FontSize = $($win['fontSize']);")
    [void]$sb.AppendLine("            public const float LineHeight = $($win['lineHeight']);")
    [void]$sb.AppendLine("            public const int FontWeight = $($win['fontWeight']);")
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine()
}
# Drop the blank line before the closing brace of Type.
$sb.Length -= [Environment]::NewLine.Length
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine()

# Motion: the easing curves as cubic-bezier control points, and the durations in milliseconds. The
# iOS spring and the PowerPoint values are left out; they belong to other outputs.
$motion = $tokens['motion']
$inv = [System.Globalization.CultureInfo]::InvariantCulture
[void]$sb.AppendLine('    /// <summary>The motion vocabulary''s timing: cubic-bezier curves (x1, y1, x2, y2) and milliseconds.</summary>')
[void]$sb.AppendLine('    public static class Motion')
[void]$sb.AppendLine('    {')
foreach ($name in $motion['easing'].Keys) {
    if ($name.StartsWith('$')) { continue }
    $v = $motion['easing'][$name]['$value'] | ForEach-Object { ([double]$_).ToString($inv) + 'f' }
    [void]$sb.AppendLine("        public static readonly (float X1, float Y1, float X2, float Y2) Ease$(Get-Pascal $name) = ($($v -join ', '));")
}
foreach ($name in $motion['duration'].Keys) {
    if ($name.StartsWith('$')) { continue }
    [void]$sb.AppendLine("        public const int Duration$(Get-Pascal $name) = $($motion['duration'][$name]['$value']['value']);")
}
[void]$sb.AppendLine("        public const int ArriveHold = $($motion['arrive']['hold']['$value']['value']);")
[void]$sb.AppendLine("        public const int StaggerStep = $($motion['stagger']['step']['$value']['value']);")
[void]$sb.AppendLine("        public const int StaggerMaxGroups = $($motion['stagger']['maxGroups']['$value']);")
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

[System.IO.File]::WriteAllText($target, $sb.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $target"
